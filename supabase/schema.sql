create or replace function public.expirar_link_acompanhamento_pedido()
returns trigger language plpgsql set search_path = public as $$
begin
  if NEW.status in ('entregue', 'cancelado') then
    NEW.tracking_token := null;
  end if;
  return NEW;
end;
$$;

