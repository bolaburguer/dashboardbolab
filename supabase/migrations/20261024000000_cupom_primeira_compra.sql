-- Aplicar no mesmo Supabase usado pelo dashboard e pelo site.
-- Não altera o cupom existente até o administrador salvar a configuração no painel.
begin;

create table if not exists public.cupons (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  descricao text not null default '',
  tipo_desconto text not null default 'percentual' check (tipo_desconto in ('percentual', 'frete_gratis')),
  valor_desconto numeric not null default 0,
  minimo_itens integer not null default 1,
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.cupons add column if not exists primeira_compra boolean not null default false;
create unique index if not exists cupom_primeira_compra_unico on public.cupons (primeira_compra) where primeira_compra;

-- Esta configuração é gravada somente pelo RPC autenticado abaixo, inclusive
-- em bancos antigos que tenham políticas amplas na tabela de cupons.
create or replace function public.proteger_cupom_primeira_compra() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if (case when TG_OP = 'DELETE' then old.primeira_compra
      when TG_OP = 'INSERT' then new.primeira_compra
      else old.primeira_compra or new.primeira_compra end)
     and current_user not in ('postgres', 'supabase_admin', 'service_role') then
    raise exception 'Edite o cupom de primeira compra pelo painel autorizado.';
  end if;
  if TG_OP = 'DELETE' then return old; end if;
  if new.primeira_compra and (length(trim(new.codigo)) not between 1 and 30
     or length(trim(new.descricao)) not between 1 and 200
     or new.minimo_itens < 1
     or new.tipo_desconto not in ('percentual', 'frete_gratis')
     or (new.tipo_desconto = 'percentual' and (new.valor_desconto <= 0 or new.valor_desconto > 100))) then
    raise exception 'Configuração do cupom inválida.';
  end if;
  return new;
end $$;
drop trigger if exists proteger_primeira_compra on public.cupons;
create trigger proteger_primeira_compra before insert or update or delete on public.cupons
for each row execute function public.proteger_cupom_primeira_compra();

alter table public.cupons enable row level security;
grant select on public.cupons to anon, authenticated;
drop policy if exists cupons_leitura_site on public.cupons;
create policy cupons_leitura_site on public.cupons for select to anon, authenticated using (true);

create or replace function public.salvar_cupom_primeira_compra(
  p_codigo text, p_descricao text, p_tipo text, p_valor numeric, p_ativo boolean
) returns void language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if auth.uid() is null or coalesce(auth.jwt()->'app_metadata'->>'role', '') <> 'admin' then
    raise exception 'Acesso permitido apenas ao administrador.';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('config-cupom-primeira-compra', 0));
  if exists (select 1 from public.cupons where upper(codigo) = upper(trim(p_codigo)) and not primeira_compra) then
    raise exception 'Este código já pertence a outro cupom.';
  end if;
  if exists (select 1 from public.cupons where primeira_compra) then
    update public.cupons set codigo = upper(trim(p_codigo)), descricao = trim(p_descricao),
      tipo_desconto = p_tipo, valor_desconto = case when p_tipo = 'frete_gratis' then 0 else p_valor end,
      ativo = p_ativo where primeira_compra;
  else
    insert into public.cupons (codigo, descricao, tipo_desconto, valor_desconto, minimo_itens, ativo, primeira_compra)
    values (upper(trim(p_codigo)), trim(p_descricao), p_tipo,
      case when p_tipo = 'frete_gratis' then 0 else p_valor end, 1, p_ativo, true);
  end if;
end $$;
revoke all on function public.salvar_cupom_primeira_compra(text,text,text,numeric,boolean) from public, anon;
grant execute on function public.salvar_cupom_primeira_compra(text,text,text,numeric,boolean) to authenticated;

create or replace function public.normalizar_whatsapp(p_telefone text) returns text
language sql immutable set search_path = public, pg_temp as $$
  select case when length(n) in (12,13) and left(n,2) = '55' then substr(n,3) else n end
  from (select regexp_replace(coalesce(p_telefone,''), '[^0-9]', '', 'g') n) x;
$$;
create index if not exists pedidos_whatsapp_normalizado on public.pedidos(public.normalizar_whatsapp(telefone));

-- O registro permanece mesmo se o pedido for excluído no painel.
-- Um checkout online reserva o benefício até a confirmação; não é liberado
-- por prazo, pois um link antigo ainda poderia ser pago posteriormente.
create table if not exists public.primeira_compra_whatsapp (
  telefone text primary key,
  cupom_id bigint not null,
  pagamento_id uuid unique,
  pedido_id bigint,
  created_at timestamptz not null default now()
);
alter table public.primeira_compra_whatsapp enable row level security;
revoke all on public.primeira_compra_whatsapp from anon, authenticated;

create or replace function public.validar_cupom_site(p_codigo text, p_telefone text, p_itens integer)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare c public.cupons; n text := public.normalizar_whatsapp(p_telefone);
begin
  select * into c from public.cupons where upper(codigo) = upper(trim(p_codigo)) and ativo limit 1;
  if not found then raise exception 'Cupom inválido ou desativado.'; end if;
  if p_itens is null or p_itens < c.minimo_itens then raise exception 'Quantidade mínima de itens não atingida.'; end if;
  if c.primeira_compra then
    if n !~ '^[1-9][1-9]9[0-9]{8}$' then raise exception 'Informe o WhatsApp com DDD antes de aplicar o cupom.'; end if;
    if exists (select 1 from public.pedidos where public.normalizar_whatsapp(telefone) = n and status <> 'cancelado')
       or exists (select 1 from public.primeira_compra_whatsapp where telefone = n and pedido_id is not null) then
      raise exception 'Este cupom é válido apenas na primeira compra deste WhatsApp.';
    end if;
    if exists (select 1 from public.primeira_compra_whatsapp where telefone = n) then
      raise exception 'Este WhatsApp já tem um pagamento de primeira compra em aberto. Conclua o pagamento anterior.';
    end if;
    if exists (select 1 from public.pagamentos_pix where public.normalizar_whatsapp(pedido->>'telefone') = n and pedido_id is null) then
      raise exception 'Este WhatsApp já tem um pagamento em aberto. Conclua o pagamento anterior antes de usar o cupom de primeira compra.';
    end if;
  end if;
  return to_jsonb(c);
end $$;
revoke all on function public.validar_cupom_site(text,text,integer) from public;
grant execute on function public.validar_cupom_site(text,text,integer) to anon, authenticated, service_role;

alter table public.pedidos add column if not exists cupom_codigo text;

create or replace function public.garantir_primeira_compra_pedido() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
declare n text := public.normalizar_whatsapp(new.telefone); c public.cupons;
  reserva public.primeira_compra_whatsapp;
  origem text := current_setting('app.pagamento_primeira_compra', true);
begin
  if new.status = 'cancelado' then return new; end if;
  if n = '' then return new; end if;
  perform pg_advisory_xact_lock(hashtextextended('primeira-compra:' || n, 0));
  select * into reserva from public.primeira_compra_whatsapp where telefone = n;
  if reserva.telefone is not null and reserva.pedido_id is null then
    if origem is distinct from reserva.pagamento_id::text then
      raise exception 'Este WhatsApp tem um pagamento de primeira compra em aberto. Conclua o pagamento anterior.';
    end if;
    -- O cupom e seu preço foram congelados quando o checkout foi reservado.
    update public.primeira_compra_whatsapp set pedido_id = new.id where telefone = n;
    return new;
  end if;
  if new.cupom_codigo is null then return new; end if;
  select * into c from public.cupons where upper(codigo) = upper(new.cupom_codigo) limit 1;
  if not found or not c.ativo then raise exception 'Cupom inválido ou desativado.'; end if;
  if c.primeira_compra then
    perform public.validar_cupom_site(c.codigo, n,
      (select coalesce(sum((i->>'quantidade')::integer),0)::integer from jsonb_array_elements(new.itens) i));
    insert into public.primeira_compra_whatsapp(telefone,cupom_id,pedido_id) values(n,c.id,new.id);
  end if;
  return new;
end $$;
drop trigger if exists garantir_primeira_compra on public.pedidos;
create trigger garantir_primeira_compra before insert on public.pedidos
for each row execute function public.garantir_primeira_compra_pedido();

create or replace function public.liberar_primeira_compra_cancelada() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if new.status = 'cancelado' and old.status <> 'cancelado' then
    perform pg_advisory_xact_lock(hashtextextended('primeira-compra:' || public.normalizar_whatsapp(old.telefone), 0));
    delete from public.primeira_compra_whatsapp where pedido_id = new.id;
  end if;
  return new;
end $$;
drop trigger if exists liberar_primeira_compra_cancelada on public.pedidos;
create trigger liberar_primeira_compra_cancelada after update of status on public.pedidos
for each row execute function public.liberar_primeira_compra_cancelada();

-- A tabela de pagamentos já é usada pela integração InfinitePay do site.
-- A reserva ocorre no mesmo INSERT do pagamento, impedindo dois checkouts simultâneos.
create or replace function public.reservar_primeira_compra_pagamento() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
declare c public.cupons; n text := public.normalizar_whatsapp(new.pedido->>'telefone');
begin
  if n = '' then return new; end if;
  perform pg_advisory_xact_lock(hashtextextended('primeira-compra:' || n, 0));
  if exists (select 1 from public.primeira_compra_whatsapp where telefone = n and pedido_id is null) then
    raise exception 'Este WhatsApp já tem um pagamento de primeira compra em aberto. Conclua o pagamento anterior.';
  end if;
  if nullif(new.pedido->>'cupom_codigo','') is null then return new; end if;
  select * into c from public.cupons where upper(codigo) = upper(new.pedido->>'cupom_codigo') limit 1;
  if not found or not c.ativo then raise exception 'Cupom inválido ou desativado.'; end if;
  if c.primeira_compra then
    perform public.validar_cupom_site(c.codigo, n,
      (select coalesce(sum((i->>'quantidade')::integer),0)::integer from jsonb_array_elements(new.pedido->'itens') i));
    insert into public.primeira_compra_whatsapp(telefone,cupom_id,pagamento_id) values(n,c.id,new.id);
  end if;
  return new;
end $$;
drop trigger if exists reservar_primeira_compra on public.pagamentos_pix;
create trigger reservar_primeira_compra before insert on public.pagamentos_pix
for each row execute function public.reservar_primeira_compra_pagamento();

-- Mantém a confirmação existente e fornece ao trigger a identidade do checkout.
create or replace function public.confirmar_pagamento_com_cupom(
  p_id uuid, p_transaction_nsu text, p_capture_method text, p_receipt_url text
) returns bigint language plpgsql security definer set search_path = public, pg_temp as $$
begin
  perform set_config('app.pagamento_primeira_compra', p_id::text, true);
  return public.confirmar_pagamento_pix(p_id => p_id, p_transaction_nsu => p_transaction_nsu,
    p_capture_method => p_capture_method, p_receipt_url => p_receipt_url);
end $$;
revoke all on function public.confirmar_pagamento_com_cupom(uuid,text,text,text) from public, anon, authenticated;
grant execute on function public.confirmar_pagamento_com_cupom(uuid,text,text,text) to service_role;

-- Só remove reservas cujo link nunca chegou a ser disponibilizado.
create or replace function public.desfazer_reserva_sem_link(p_id uuid) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  delete from public.primeira_compra_whatsapp r where r.pagamento_id = p_id and r.pedido_id is null
    and exists (select 1 from public.pagamentos_pix p where p.id = p_id and p.checkout_url is null and p.pedido_id is null);
  delete from public.pagamentos_pix where id = p_id and checkout_url is null and pedido_id is null;
end $$;
revoke all on function public.desfazer_reserva_sem_link(uuid) from public, anon, authenticated;
grant execute on function public.desfazer_reserva_sem_link(uuid) to service_role;
commit;
