-- Cupons configurados pelo dashboard e consultados pelo site.
create table if not exists public.cupons (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  descricao text not null,
  tipo_desconto text not null check (tipo_desconto in ('percentual', 'frete_gratis')),
  valor_desconto numeric(5,2) not null default 0 check (valor_desconto between 0 and 100),
  minimo_itens integer not null default 0 check (minimo_itens >= 0),
  ativo boolean not null default false,
  created_at timestamptz not null default now(),
  constraint cupons_codigo_maiusculo check (codigo = upper(codigo))
);

grant select, insert, update, delete on public.cupons to anon, authenticated;
grant usage, select on sequence public.cupons_id_seq to anon, authenticated;
grant all on public.cupons to service_role;

alter table public.cupons enable row level security;

create policy "cupons_public_all" on public.cupons
  for all to anon, authenticated using (true) with check (true);
